package expo.modules.terminalemulator

import android.content.Context
import android.os.Build
import android.os.SystemClock
import android.util.Log
import java.io.File
import java.util.concurrent.TimeUnit

/**
 * MCPBridge — spawns/stops scripts/shelly-mcp-server.js, a minimal MCP
 * (Model Context Protocol) server exposing a small set of read tools
 * (git_status, list_agents, list_repos, device_status; read_terminal_output,
 * read_logs / get_settings and the exec/write tools only when their settings
 * are on) to an MCP
 * client (Claude Code, Claude Desktop) on the same network. See that
 * script's own doc comment for the protocol details, why it targets the
 * older initialize+Mcp-Session-Id flow rather than the newer stateless
 * 2026-07-28 revision, and the file-queue IPC bridge (mirrored on the RN
 * side by lib/mcp-server-bridge.ts) it uses to reach RN's JS state.
 *
 * Lifecycle: McpServerSupervisor owns starting, watching and restarting
 * this process (and McpServerService keeps the app process in the
 * foreground while it is wanted); this object only spawns / stops it.
 *
 * Structurally a near-duplicate of A2ABridge.kt (long-lived process, same
 * ProcessBuilder + linker64 spawn mechanics) —
 * kept as a separate class/process/port rather than merged into one server
 * because MCP and A2A are different protocols with different request
 * shapes; sharing a listener would mean branching protocol dispatch inside
 * one script for no real benefit at this scale. Revisit if both grow.
 */
object MCPBridge {
    private const val TAG = "MCPBridge"
    private const val PORT = 8767 // keep in sync with lib/mcp-token.ts MCP_SERVER_PORT
    private const val STOP_GRACE_MS = 2000L

    private var process: Process? = null
    /** The bridge key the running process was started with (never logged). */
    private var processBridgeKey: String? = null
    /** Token + tool switches the running process was started with (never logged). */
    private var processToken: String? = null
    private var processExec = false
    private var processReadTerminal = false
    private var processDiagnostics = false
    private var processTypedOps = false
    private val BRIDGE_KEY_RE = Regex("^[0-9a-f]{64}$")
    /** Same rule as the script's TOKEN_RE: one stdin line, no spaces / controls. */
    private val TOKEN_RE = Regex("^[\\x21-\\x7e]{1,1024}$")

    fun isRunning(): Boolean = process?.let { isAlive(it) } == true

    // Process.isAlive / waitFor(long, TimeUnit) / destroyForcibly() are API 26;
    // minSdk is 24, so API 24/25 use exitValue() polling and destroy() only.
    private fun isAlive(proc: Process): Boolean {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) return proc.isAlive
        return try {
            proc.exitValue()
            false
        } catch (_: IllegalThreadStateException) {
            true
        }
    }

    /** Waits up to [timeoutMs] for [proc] to exit; true if it did. */
    private fun waitForExit(proc: Process, timeoutMs: Long): Boolean {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) {
            return proc.waitFor(timeoutMs, TimeUnit.MILLISECONDS)
        }
        val deadline = SystemClock.uptimeMillis() + timeoutMs
        while (isAlive(proc)) {
            if (SystemClock.uptimeMillis() >= deadline) return false
            Thread.sleep(50)
        }
        return true
    }

    private fun forceKill(proc: Process) {
        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.O) proc.destroyForcibly() else proc.destroy()
    }

    /**
     * [exec] / [readTerminal] / [diagnostics] mirror the RN settings
     * mcpExecEnabled / mcpReadTerminalEnabled / mcpDiagnosticsEnabled, and
     * [typedOps] mirrors mcpTypedOpsEnabled. The
     * script only reads them at startup (it hides run_command / write_file /
     * read_terminal_output / read_logs / get_settings from tools/list when
     * off), so RN restarts the server whenever any of them changes
     * (hooks/use-mcp-server-bridge.ts). RN still refuses those calls itself.
     *
     * [bridgeKey] (64 hex, generated by RN per start, held only in RN memory)
     * signs the queue requests the script writes (lib/mcp-request-auth.ts);
     * RN drops any request file without a valid MAC. A running process
     * started with another key is restarted, since RN would reject every
     * request it signs.
     *
     * [token] (the MCP bearer token) and [bridgeKey] are both secrets and go
     * on the process's stdin, never in its environment (/proc/<pid>/environ
     * is readable by the same uid). Framing, kept in sync with
     * scripts/shelly-mcp-server.js readStartupSecretsFromStdin():
     *   line 1: token      (printable ASCII 0x21-0x7e, 1..1024 chars)
     *   line 2: bridge key (64 lowercase hex)
     * each terminated by '\n', then stdin is closed (EOF). Neither is logged.
     */
    @Synchronized
    fun start(context: Context, token: String, exec: Boolean, readTerminal: Boolean, diagnostics: Boolean, typedOps: Boolean, bridgeKey: String): Boolean {
        if (!TOKEN_RE.matches(token)) {
            // Also guarantees the token can't break the stdin line framing.
            Log.e(TAG, "no or malformed token provided")
            return false
        }
        if (!BRIDGE_KEY_RE.matches(bridgeKey)) {
            Log.e(TAG, "invalid bridge key")
            return false
        }
        // Ingress taint: from the first MCP start on, deleting the taint store reads as "unreadable".
        AgentIngressTaint.seal(context)
        if (isRunning()) {
            // Reuse the process only when it runs with exactly this key, token
            // and tool switches: a process started with other switches (e.g.
            // exec ON while the owner just turned it OFF) or another token must
            // never keep serving.
            if (processBridgeKey == bridgeKey && processToken == token &&
                processExec == exec && processReadTerminal == readTerminal &&
                processDiagnostics == diagnostics && processTypedOps == typedOps
            ) return true
            Log.i(TAG, "restarting the MCP server (new bridge key or changed settings)")
            stop()
        }

        val homeDir = HomeInitializer.getHomeDir(context)
        val libDir = LibExtractor.getLibDir(context)
        val scriptPath = File(homeDir, ".shelly-mcp-server.js").absolutePath
        val nodePath = File(libDir, "node").absolutePath
        val queueDir = File(homeDir, ".shelly-mcp-queue")
        queueDir.mkdirs()

        if (!File(scriptPath).exists() || !File(nodePath).exists()) {
            Log.e(TAG, "MCP runtime not extracted yet (script or node binary missing)")
            return false
        }

        val pb = ProcessBuilder("/system/bin/linker64", nodePath, scriptPath, queueDir.absolutePath, PORT.toString())
        pb.environment()["LD_LIBRARY_PATH"] = libDir.absolutePath
        pb.environment()["SHELLY_LIB_DIR"] = libDir.absolutePath
        pb.environment()["HOME"] = homeDir.absolutePath
        // No token or bridge key in the environment: /proc/<pid>/environ is
        // readable by the same uid, so both go on the process's stdin below
        // (the script holds them in memory only). The switches are not
        // secrets. Explicit "0" so an inherited value can never turn a tool on.
        pb.environment()["SHELLY_MCP_EXEC"] = if (exec) "1" else "0"
        pb.environment()["SHELLY_MCP_READ_TERMINAL"] = if (readTerminal) "1" else "0"
        pb.environment()["SHELLY_MCP_DIAGNOSTICS"] = if (diagnostics) "1" else "0"
        pb.environment()["SHELLY_MCP_TYPED_OPS"] = if (typedOps) "1" else "0"
        pb.directory(homeDir)
        pb.redirectErrorStream(false)
        return try {
            val proc = pb.start()
            // Hand token + key over on stdin (line 1 token, line 2 key, '\n'
            // each — explicit, not newLine()) and close it, so neither ever
            // sits in the process environment. At most ~1.1 KB, so it can't
            // block on a pipe; a failure here means the process is already gone.
            try {
                proc.outputStream.bufferedWriter(Charsets.US_ASCII).use {
                    it.write(token)
                    it.write("\n")
                    it.write(bridgeKey)
                    it.write("\n")
                    it.flush()
                }
            } catch (e: Exception) {
                Log.e(TAG, "failed to pass the token and bridge key to the MCP server: ${e.message}")
                runCatching { forceKill(proc) }
                return false
            }
            process = proc
            processBridgeKey = bridgeKey
            processToken = token
            processExec = exec
            processReadTerminal = readTerminal
            processDiagnostics = diagnostics
            processTypedOps = typedOps
            Thread {
                try {
                    proc.errorStream.bufferedReader().forEachLine { Log.i(TAG, it) }
                } catch (_: Exception) {}
            }.apply { name = "MCPBridge-stderr"; start() }
            true
        } catch (e: Exception) {
            Log.e(TAG, "failed to spawn MCP server: ${e.message}")
            false
        }
    }

    /**
     * Stops the server and waits for the process to actually exit, so a
     * restart (token regeneration, see lib/mcp-token.ts) never overlaps an
     * old process that still holds the port and still accepts the old token.
     * SIGTERM first (the script closes every open connection and exits), then
     * SIGKILL if it hasn't exited within the grace period.
     */
    @Synchronized
    fun stop() {
        val proc = process ?: return
        process = null
        processBridgeKey = null
        processToken = null
        try {
            proc.destroy()
            if (!waitForExit(proc, STOP_GRACE_MS)) {
                Log.w(TAG, "MCP server did not exit on SIGTERM; killing")
                forceKill(proc)
                if (!waitForExit(proc, STOP_GRACE_MS)) {
                    Log.e(TAG, "MCP server still alive after forced kill")
                }
            }
        } catch (e: InterruptedException) {
            Thread.currentThread().interrupt()
            runCatching { forceKill(proc) }
        } catch (_: Exception) {
            runCatching { forceKill(proc) }
        }
    }
}
