/**
 * Expo config plugin: sign Android release builds with Shelly's private
 * release key instead of the public React Native / Expo debug.keystore.
 *
 * Why: until this plugin, every shipped release APK was signed with the
 * well-known debug keystore (cert SHA-256 FA:C6:17:45:...:3B:9C) that ships
 * inside every RN/Expo template. Anyone could sign a fake "Shelly update"
 * that Android would accept as an in-place upgrade (keeping all app data,
 * SecureStore and the ClosePaw trusted-caller pin).
 *
 * `expo prebuild` regenerates android/ from config plugins (hand edits to
 * android/app/build.gradle are not durable), so the signing config is
 * injected here via withAppBuildGradle.
 *
 * Signing is selected by SHELLY_SIGNING_MODE (env var or Gradle property):
 *   - release       Sign with the release keystore from
 *                   SHELLY_RELEASE_STORE_FILE / SHELLY_RELEASE_STORE_PASSWORD /
 *                   SHELLY_RELEASE_KEY_ALIAS / SHELLY_RELEASE_KEY_PASSWORD.
 *                   Missing or unreadable keystore => the build FAILS. There
 *                   is no silent fallback to the debug key.
 *   - rotation      Gradle emits an UNSIGNED release APK; CI then signs it
 *                   with apksigner using APK Signature Scheme v3 key rotation
 *                   (old signer = legacy debug key, next signer = release
 *                   key, lineage signing/shelly-signing-lineage.bin). API 28+
 *                   installs signed by the debug key update in place and are
 *                   rotated to the release key; the lineage revokes the old
 *                   key's rollback capability so a debug-only APK can no
 *                   longer update a rotated install. See
 *                   .github/workflows/build-android.yml "Sign APK with v3 key
 *                   rotation". If CI forgets to sign, the apksigner verify
 *                   step fails on the unsigned APK (fail closed).
 *   - legacy-debug  Explicitly sign with the debug key (pre-rotation builds).
 *   - (unset)       Local developer builds: debug key. Refused when CI=true so
 *                   CI can never ship a debug-signed APK by forgetting the mode.
 */
const { withAppBuildGradle } = require("expo/config-plugins");

const MARKER = "@shelly-release-signing";

const PRELUDE = `// ${MARKER} begin (generated by plugins/with-release-signing.js — do not edit)
def shellySigningValue = { String name ->
    def value = System.getenv(name)
    if (value == null || value.trim().isEmpty()) {
        def prop = project.findProperty(name)
        value = prop == null ? null : prop.toString()
    }
    return (value == null || value.trim().isEmpty()) ? null : value.trim()
}
def shellySigningMode = shellySigningValue('SHELLY_SIGNING_MODE')
def shellyReleaseStoreFile = shellySigningValue('SHELLY_RELEASE_STORE_FILE')
def shellyReleaseStorePassword = shellySigningValue('SHELLY_RELEASE_STORE_PASSWORD')
def shellyReleaseKeyAlias = shellySigningValue('SHELLY_RELEASE_KEY_ALIAS')
def shellyReleaseKeyPassword = shellySigningValue('SHELLY_RELEASE_KEY_PASSWORD')
if (shellySigningMode != null && !(shellySigningMode in ['release', 'rotation', 'legacy-debug'])) {
    throw new GradleException("SHELLY_SIGNING_MODE must be 'release', 'rotation' or 'legacy-debug' (got '\${shellySigningMode}')")
}
if (shellySigningMode == null && 'true'.equalsIgnoreCase(System.getenv('CI') ?: '')) {
    throw new GradleException("SHELLY_SIGNING_MODE is required on CI; refusing to fall back to the public debug keystore")
}
def shellyUseReleaseSigning = shellySigningMode == 'release'
def shellyLeaveReleaseUnsigned = shellySigningMode == 'rotation'
if (shellyUseReleaseSigning) {
    def missing = []
    if (shellyReleaseStoreFile == null) missing << 'SHELLY_RELEASE_STORE_FILE'
    if (shellyReleaseStorePassword == null) missing << 'SHELLY_RELEASE_STORE_PASSWORD'
    if (shellyReleaseKeyAlias == null) missing << 'SHELLY_RELEASE_KEY_ALIAS'
    if (shellyReleaseKeyPassword == null) missing << 'SHELLY_RELEASE_KEY_PASSWORD'
    if (!missing.isEmpty()) {
        throw new GradleException("SHELLY_SIGNING_MODE=release but release signing is not configured: missing \${missing.join(', ')}")
    }
    if (!new File(shellyReleaseStoreFile).isFile()) {
        throw new GradleException("SHELLY_SIGNING_MODE=release but SHELLY_RELEASE_STORE_FILE does not exist")
    }
}
// ${MARKER} end
`;

const RELEASE_SIGNING_CONFIG = `
        // ${MARKER}: release key, only defined when SHELLY_SIGNING_MODE=release
        if (shellyUseReleaseSigning) {
            release {
                storeFile new File(shellyReleaseStoreFile)
                storeType 'pkcs12'
                storePassword shellyReleaseStorePassword
                keyAlias shellyReleaseKeyAlias
                keyPassword shellyReleaseKeyPassword
            }
        }`;

const RELEASE_BUILD_TYPE_SIGNING =
  `signingConfig shellyLeaveReleaseUnsigned ? null : (shellyUseReleaseSigning ? signingConfigs.release : signingConfigs.debug) // ${MARKER}`;

function applyReleaseSigning(source) {
  if (source.includes(`${MARKER} begin`)) {
    return source;
  }
  let contents = source;

  // 1. Release buildType: switch signingConfig. Done before step 2 so the
  //    search cannot match the `release {` block we add to signingConfigs.
  const buildTypeRe = /(buildTypes\s*\{[\s\S]*?\n\s*release\s*\{[\s\S]*?)signingConfig\s+signingConfigs\.debug/;
  if (!buildTypeRe.test(contents)) {
    throw new Error("with-release-signing: could not find buildTypes.release signingConfig in app/build.gradle");
  }
  contents = contents.replace(buildTypeRe, `$1${RELEASE_BUILD_TYPE_SIGNING}`);

  // 2. signingConfigs: add the (conditional) release config after debug.
  const signingConfigsRe = /(signingConfigs\s*\{\s*\n\s*debug\s*\{[^}]*\})/;
  if (!signingConfigsRe.test(contents)) {
    throw new Error("with-release-signing: could not find signingConfigs.debug in app/build.gradle");
  }
  contents = contents.replace(signingConfigsRe, `$1${RELEASE_SIGNING_CONFIG}`);

  // 3. Prelude (mode resolution + fail-closed checks) right before android {.
  const androidRe = /^android\s*\{/m;
  if (!androidRe.test(contents)) {
    throw new Error("with-release-signing: could not find top-level android { block in app/build.gradle");
  }
  contents = contents.replace(androidRe, (m) => `${PRELUDE}\n${m}`);

  return contents;
}

function withReleaseSigning(config) {
  return withAppBuildGradle(config, (config) => {
    if (config.modResults.language !== "groovy") {
      throw new Error("with-release-signing: only Groovy app/build.gradle is supported");
    }
    config.modResults.contents = applyReleaseSigning(config.modResults.contents);
    return config;
  });
}

module.exports = withReleaseSigning;
module.exports.applyReleaseSigning = applyReleaseSigning;
module.exports.MARKER = MARKER;
